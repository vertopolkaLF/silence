//! Embeds the settings UI's image assets. Every file in the listed asset
//! directories is reachable from GPUI as "<dir>/<file name>".
use std::{env, fmt::Write as _, fs, path::Path};

const EMBEDDED_DIRS: &[&str] = &["icons", "gamepad", "flags"];
const EMBEDDED_FILES: &[&str] = &["app.png"];

fn main() {
    let root = env::var("CARGO_MANIFEST_DIR").unwrap();
    let assets = Path::new(&root).join("assets");
    let mut arms = String::new();
    let mut add = |key: String, path: &Path| {
        let path = path.to_string_lossy().replace('\\', "/");
        writeln!(arms, "        {key:?} => include_bytes!({path:?}),").unwrap();
    };

    for dir in EMBEDDED_DIRS {
        let path = assets.join(dir);
        println!("cargo:rerun-if-changed={}", path.display());
        let mut entries: Vec<_> = fs::read_dir(&path)
            .unwrap()
            .filter_map(|entry| entry.ok().map(|entry| entry.path()))
            .filter(|path| path.is_file())
            .collect();
        entries.sort();
        for file in entries {
            let name = file.file_name().unwrap().to_string_lossy().into_owned();
            add(format!("{dir}/{name}"), &file);
        }
    }
    for file in EMBEDDED_FILES {
        let path = assets.join(file);
        println!("cargo:rerun-if-changed={}", path.display());
        add(file.to_string(), &path);
    }

    let source = format!(
        "/// Generated by build.rs from the assets directory.\n\
         pub(crate) fn embedded_asset(path: &str) -> Option<&'static [u8]> {{\n    \
         Some(match path {{\n{arms}        _ => return None,\n    }})\n}}\n"
    );
    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("embedded_assets.rs");
    fs::write(out, source).unwrap();
}
