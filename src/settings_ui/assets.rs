//! Embedded images and fonts for the settings window.
use anyhow::Result;
use gpui::{App, AssetSource, SharedString};
use std::borrow::Cow;

include!(concat!(env!("OUT_DIR"), "/embedded_assets.rs"));

/// Serves "icons/<name>.svg", "gamepad/<name>.png", "flags/<name>.svg" and
/// "app.png" from the binary.
pub(crate) struct SettingsAssets;

impl AssetSource for SettingsAssets {
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>> {
        Ok(embedded_asset(path).map(Cow::Borrowed))
    }

    fn list(&self, _path: &str) -> Result<Vec<SharedString>> {
        Ok(Vec::new())
    }
}

/// Path of a Solar/Iconify icon in `assets/icons`.
pub(crate) fn icon(name: &str) -> SharedString {
    SharedString::from(format!("icons/{name}.svg"))
}

macro_rules! settings_fonts {
    ($($file:literal),* $(,)?) => {
        &[$(include_bytes!(concat!("../../assets/fonts/settings/", $file)) as &[u8]),*]
    };
}

/// Static instances generated by `scripts/build_settings_fonts.py`.
const SETTINGS_FONTS: &[&[u8]] = settings_fonts![
    "PlusJakartaSans-400.ttf",
    "PlusJakartaSans-500.ttf",
    "PlusJakartaSans-560.ttf",
    "PlusJakartaSans-600.ttf",
    "BricolageGrotesque-500.ttf",
    "BricolageGrotesque-600.ttf",
    "BricolageGrotesque-620.ttf",
    "BricolageGrotesque-650.ttf",
    "BricolageGrotesque-700.ttf",
    "BricolageGrotesque-760.ttf",
    "BricolageGrotesque-800.ttf",
    "BricolageGrotesqueDisplay-650.ttf",
    "BricolageGrotesqueDisplay-700.ttf",
    "BricolageGrotesqueDisplay-800.ttf",
];

/// Registers the UI fonts plus the bundled overlay families, which the
/// overlay font picker previews.
pub(crate) fn register_fonts(cx: &mut App) {
    let mut fonts: Vec<Cow<'static, [u8]>> =
        SETTINGS_FONTS.iter().map(|data| Cow::Borrowed(*data)).collect();
    for family in crate::gpui_overlay::fonts::FAMILIES {
        if let Some(data) = crate::gpui_overlay::fonts::embedded(family) {
            fonts.push(data);
        }
    }
    if let Err(error) = cx.text_system().add_fonts(fonts) {
        eprintln!("settings fonts: {error:#}");
    }
}
